"""Auto-set a brand's canonical mark in its own brand.yaml, comments preserved.

The GUI's brand card renders ``mark_url`` from the ``brand.mark`` block in
brand.yaml (see ``api/routes.py:_mark_url``). Historically that block was only
ever written by hand, so a brand whose logo arrived through the upload route or
was approved out of a generation run still rendered markless. This module is the
one writer both of those flows call: when a logo lands (import) or is accepted
(approval) and the brand's own file has no ``mark`` yet, the block is inserted;
an existing mark is never touched, so a curated choice always wins.

Two properties matter here:

* The presence check reads the brand's OWN raw brand.yaml, not the loaded
  (parent-merged) Brand. The merge replaces the ``brand:`` block wholesale from
  the child, so the raw check matches what the merged brand actually serves --
  and a child can never be denied its own mark by state it does not have.
* The write is a comment-preserving textual insert, not a parse-and-redump.
  Hand-authored kits (meeting-ops and friends) carry comments that a
  ``yaml.safe_dump`` round trip would silently destroy. The fragment is
  generated by ``yaml.safe_dump`` (so quoting/escaping is always valid YAML),
  indented to the brand block's own key depth, and inserted right after the
  ``display_name:`` line (falling back to ``slug:``). The result is re-parsed
  before it is written: if the insert would not produce a document carrying the
  expected mark, nothing is written at all.

Failures are logged and swallowed: setting a mark is a bonus on top of an
upload/approval that already succeeded, so this helper never raises.
"""
from __future__ import annotations

import logging
from pathlib import Path

import yaml

from .atomic_write import atomic_write_text
from .brand_loader import current_kits_dir

_log = logging.getLogger("brand_ops.brand_mark")


def _insertion_index(lines: list[str]) -> int | None:
    """The line index after which the mark fragment goes, or None.

    Scans for the top-level ``brand:`` mapping, then within it for the
    ``display_name:`` key line, falling back to the ``slug:`` key line. A key
    whose value opens a block scalar (``|`` / ``>``) is skipped -- inserting
    inside a block scalar would corrupt it (``description: |`` is common; a
    block-scalar display_name or slug is not, but the guard is cheap). Comment
    and blank lines never terminate the block; the first non-indented,
    non-comment content line after ``brand:`` does.
    """
    in_brand = False
    fallback: int | None = None
    for i, line in enumerate(lines):
        content = line.rstrip("\n")
        if not in_brand:
            # The top-level block opener, tolerating trailing spaces/comments.
            if content.split("#", 1)[0].rstrip() == "brand:":
                in_brand = True
            continue
        stripped = content.strip()
        if not stripped or stripped.startswith("#"):
            continue
        if not content[0].isspace():
            # A new top-level key: the brand block is over.
            break
        key = stripped.split(":", 1)[0].strip()
        value = stripped.split(":", 1)[1].strip() if ":" in stripped else ""
        opens_block_scalar = value.startswith(("|", ">"))
        if key == "display_name" and not opens_block_scalar:
            return i
        if key == "slug" and not opens_block_scalar and fallback is None:
            fallback = i
    return fallback


def maybe_set_brand_mark(
    brand_slug: str,
    asset_type: str,
    file: str,
    kind: str,
    kits_dir: Path | None = None,
) -> bool:
    """Set ``brand.mark`` in ``<kits>/<brand_slug>/brand.yaml`` if absent.

    Args:
        brand_slug: The brand whose own file is edited (never the parent's).
        asset_type: The mark's asset type key, e.g. ``"logo"``.
        file: The stored file name the mark points at (the on-disk name, which
            for an upload may carry a collision suffix).
        kind: Which tree the file lives in: ``"imported"`` for an upload,
            ``"generated"`` for an approved generation (approval moves no
            files, so the mark must name the tree the bytes are actually in).
        kits_dir: Override the kits root; defaults to the request's
            ``current_kits_dir()`` so the scoped and unscoped paths both work.

    Returns True when a mark was written, False otherwise (already marked,
    missing/invalid file, or any error). Never raises and never overwrites.
    """
    try:
        root = kits_dir or current_kits_dir()
        path = root / brand_slug / "brand.yaml"
        try:
            text = path.read_text(encoding="utf-8")
        except OSError as exc:
            _log.warning("auto-mark %s: brand.yaml unreadable: %s", brand_slug, exc)
            return False

        try:
            doc = yaml.safe_load(text)
        except yaml.YAMLError as exc:
            _log.warning("auto-mark %s: brand.yaml does not parse: %s", brand_slug, exc)
            return False
        if not isinstance(doc, dict) or not isinstance(doc.get("brand"), dict):
            _log.warning("auto-mark %s: brand.yaml has no brand block", brand_slug)
            return False
        if doc["brand"].get("mark") is not None:
            # A mark already chosen (by hand or by an earlier import) wins.
            return False

        # Build the fragment through safe_dump so the values are always valid
        # YAML (quoting, escaping), then indent it to the brand block's own key
        # depth so it nests as a sibling of display_name.
        fragment = yaml.safe_dump(
            {"mark": {"asset_type": asset_type, "file": file, "kind": kind}},
            sort_keys=False,
            default_flow_style=False,
            allow_unicode=True,
        )
        lines = text.splitlines(keepends=True)
        idx = _insertion_index(lines)
        if idx is None:
            _log.warning(
                "auto-mark %s: no display_name/slug line to anchor the mark", brand_slug
            )
            return False
        indent = lines[idx][: len(lines[idx]) - len(lines[idx].lstrip())]
        indented = "".join(f"{indent}{line}\n" for line in fragment.splitlines())
        new_text = "".join(lines[: idx + 1]) + indented + "".join(lines[idx + 1 :])

        # Prove the insert before writing it: the edited text must still parse
        # and must carry exactly the mark we meant to add.
        try:
            new_doc = yaml.safe_load(new_text)
        except yaml.YAMLError as exc:
            _log.warning("auto-mark %s: inserted text does not parse: %s", brand_slug, exc)
            return False
        written = (
            new_doc.get("brand", {}).get("mark") if isinstance(new_doc, dict) else None
        )
        if written != {"asset_type": asset_type, "file": file, "kind": kind}:
            _log.warning("auto-mark %s: inserted mark did not land where expected", brand_slug)
            return False

        atomic_write_text(path, new_text)
        _log.info(
            "auto-mark %s: canonical mark set to %s/%s (%s)",
            brand_slug,
            asset_type,
            file,
            kind,
        )
        return True
    except Exception as exc:  # noqa: BLE001 - a mark is a bonus, never a failure
        _log.warning("auto-mark %s: unexpected failure: %s", brand_slug, exc)
        return False


__all__ = ["maybe_set_brand_mark"]
